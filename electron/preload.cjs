// Puente seguro entre la interfaz y Windows
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('native', {
  readData: () => ipcRenderer.invoke('data:read'),
  writeData: (text) => ipcRenderer.invoke('data:write', text),
  writeDataSync: (text) => ipcRenderer.sendSync('data:writeSync', text),
  saveFile: (id, b64) => ipcRenderer.invoke('file:save', id, b64),
  readFile: (id) => ipcRenderer.invoke('file:read', id),
  deleteFile: (id) => ipcRenderer.invoke('file:delete', id),
  fileExists: (id) => ipcRenderer.invoke('file:exists', id),
  http: (method, url, body) => ipcRenderer.invoke('http', method, url, body),
  request: (opts) => ipcRenderer.invoke('request', opts),
  multipart: (opts) => ipcRenderer.invoke('multipart', opts),
  googleAuth: (authUrlBase) => ipcRenderer.invoke('google:auth', authUrlBase),
  openFile: (id, name) => ipcRenderer.invoke('file:open', id, name),
  exportFile: (filename, text) => ipcRenderer.invoke('export:save', filename, text),
  notify: (title, body) => ipcRenderer.invoke('notify', title, body),
  setAutostart: (on) => ipcRenderer.invoke('autostart', on),
  showWindow: () => ipcRenderer.invoke('window:show'),
  setCloseToTray: (on) => ipcRenderer.invoke('closeToTray', on),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, u) => cb(u)),
  listApps: () => ipcRenderer.invoke('apps:list'),
  openApp: (p) => ipcRenderer.invoke('apps:open', p),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  pickDocsFolder: () => ipcRenderer.invoke('docs:pickFolder'),
  searchDocs: (opts) => ipcRenderer.invoke('docs:search', opts),
  readDoc: (opts) => ipcRenderer.invoke('docs:read', opts),
  openDoc: (opts) => ipcRenderer.invoke('docs:open', opts),
  windowFocused: () => ipcRenderer.invoke('window:focused'),
  bubbleShow: () => ipcRenderer.invoke('bubble:show'),
  bubbleHide: () => ipcRenderer.invoke('bubble:hide'),
  bubbleState: (s) => ipcRenderer.send('bubble:state', s),
  bubbleLevel: (l) => ipcRenderer.send('bubble:level', l),
  onBubble: (cb) => ipcRenderer.on('bubble', (_e, d) => cb(d)),
  onSystemResume: (cb) => ipcRenderer.on('system-resume', () => cb()),
});
